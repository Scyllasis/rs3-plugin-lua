const GEN_HEADER = '-- Generated by RS3 Style Studio from .rs3/styles.json.';

const isIdent = s => /^[A-Za-z_][A-Za-z0-9_]*$/.test(s);
const keyExpr = k => /^\d+$/.test(k) ? k : 'ui.StyleValue' + k.split('.').map(s => isIdent(s) ? '.' + s : '[' + JSON.stringify(s) + ']').join('');
const valueExpr = (k, v) => /(^|\.)rgb$/i.test(k) && v >= 0 ? '0x' + (v >>> 0).toString(16).toUpperCase().padStart(6, '0') : String(Math.trunc(v));

/** styles.lua source for a spec. Parents that are other custom styles are emitted first. */
function generateLua(spec) {
  const styles = (spec.styles || []).filter(s => s.name && isIdent(s.name));
  const byName = new Map(styles.map(s => [s.name, s]));
  const order = [], state = new Map();
  const visit = s => {
    if (state.get(s.name) === 2) return;
    if (state.get(s.name) === 1) return; // cycle: leave as is
    state.set(s.name, 1);
    if (s.parent && s.parent.startsWith('custom:') && byName.has(s.parent.slice(7))) visit(byName.get(s.parent.slice(7)));
    state.set(s.name, 2);
    order.push(s);
  };
  styles.forEach(visit);
  const out = [GEN_HEADER, '-- Edit styles with "RS3: Open Style Studio"; changes made directly here are overwritten.', '', 'local Styles = {}', ''];
  for (const s of order) {
    if (s.note) out.push('-- ' + String(s.note).replace(/\n/g, ' '));
    out.push(`Styles.${s.name} = ${Math.trunc(Number(s.id) || 0)}`);
    out.push('do');
    out.push(`  local s = ui.StyleSheets[Styles.${s.name}]`);
    if (s.parent) {
      const p = s.parent.startsWith('custom:') ? `Styles.${s.parent.slice(7)}` : `id.StyleSheet.${s.parent}`;
      out.push(`  s.parent = ui.StyleSheets[${p}]`);
    }
    for (const v of s.values || []) {
      if (!v.key || v.value === '' || v.value == null || !Number.isFinite(Number(v.value))) continue;
      out.push(`  s[${keyExpr(v.key)}] = ${valueExpr(v.key, Number(v.value))}`);
    }
    out.push('end', '');
  }
  out.push('return Styles', '');
  return out.join('\n');
}

const DISCOVERY_LUA = `-- RS3 Style Studio: lists ui.StyleValue keys and the values of the built-in stylesheets.
-- Run it in the beta/dev client, then copy the console lines (SV|..., SS|...) into the
-- Style Studio's "Discover keys" tab. Remove this code from your real plugin afterwards.
local found = {}
local function walk(t, path, depth)
  if depth > 8 then return end
  local ok, f, s, c = pcall(pairs, t)
  if not ok then log("SVERR|" .. path .. "|cannot list (" .. type(t) .. ")") return end
  for k, v in f, s, c do
    local p = path == "" and tostring(k) or (path .. "." .. tostring(k))
    if type(v) == "number" then
      found[#found + 1] = { p, v }
      log("SV|" .. p .. "|" .. tostring(v))
    elseif type(v) == "table" or type(v) == "userdata" then
      walk(v, p, depth + 1)
    end
  end
end
walk(ui.StyleValue, "", 0)
local names = { ${BUILTINS.flatMap(b => b.ids).map(n => JSON.stringify(n)).join(', ')} }
for _, name in ipairs(names) do
  local okId, sid = pcall(function() return id.StyleSheet[name] end)
  local sheet = okId and sid and ui.StyleSheets:Find(sid)
  if sheet then
    for _, kv in ipairs(found) do
      -- GetValue crashes the client for keys of 2^31 and above, so those are listed but not read
      local key = kv[2]
      if math.type(key) == "integer" and key >= 0 and key < 0x80000000 then
        local okV, v = pcall(function() return sheet:GetValue(key) end)
        if okV and v ~= nil then log("SS|" .. name .. "|" .. kv[1] .. "|" .. tostring(v)) end
      end
    end
  end
end
log("SVDONE|" .. #found)
`;

function parseDiscovery(text) {
  const keys = {}, sheets = {}, errors = [];
  let done = null;
  for (const line of String(text).split(/\r?\n/)) {
    let m;
    if ((m = line.match(/SV\|([^|\s]+)\|(-?\d+)/))) keys[m[1]] = Number(m[2]);
    else if ((m = line.match(/SS\|([A-Z0-9_]+)\|([^|\s]+)\|(-?\d+)/))) (sheets[m[1]] = sheets[m[1]] || {})[m[2]] = Number(m[3]);
    else if ((m = line.match(/SVERR\|([^|]*)\|(.*)$/))) errors.push((m[1] || 'ui.StyleValue') + ': ' + m[2]);
    else if ((m = line.match(/SVDONE\|(\d+)/))) done = Number(m[1]);
  }
  return { keys, sheets, errors, done };
}

/** LuaLS annotations so discovered keys autocomplete under ui.StyleValue. */
function generateAnnotations(keys) {
  const tree = {};
  for (const k of Object.keys(keys)) {
    const segs = k.split('.');
    if (!segs.every(isIdent)) continue;
    let node = tree;
    segs.forEach((s, i) => {
      if (i === segs.length - 1) { if (typeof node[s] !== 'object') node[s] = keys[k]; }
      else { if (typeof node[s] !== 'object') node[s] = {}; node = node[s]; }
    });
  }
  const out = ['---@meta', '-- Generated by RS3 Style Studio from keys discovered in the dev client (.rs3/stylevalues.json).', '-- Editor-only: you do not need to ship the .rs3 folder with your plugin.', ''];
  // fields the extension's library already declares (documented keys)
  const builtIn = new Set(['ui.StyleValueKeys.button', 'ui.StyleValueKeys.button.tint', 'ui.StyleValueKeys.button.tint.rgb', 'ui.StyleValueKeys.button.tint.alpha']);
  const emit = (node, cls) => {
    const fields = Object.entries(node).filter(([k]) => !builtIn.has(`${cls}.${k}`))
      .map(([k, v]) => typeof v === 'object' ? `---@field ${k} ${cls}.${k}` : `---@field ${k} integer Property key ${v}.`);
    if (fields.length) out.push(`---@class ${cls}`, ...fields, '');
    for (const [k, v] of Object.entries(node)) if (typeof v === 'object') emit(v, `${cls}.${k}`);
  };
  emit(tree, 'ui.StyleValueKeys');
  return out.join('\n');
}

